export function householdTasksLocale(hass) {
  const language = hass?.locale?.language || hass?.language || navigator.language || "en";
  return String(language).toLowerCase().startsWith("de") ? "de" : "en";
}

export function householdTasksLocaleTag(hass) {
  return householdTasksLocale(hass) === "de" ? "de-DE" : "en-US";
}

export function householdTasksText(source, hass) {
  return householdTasksLocale(hass) === "de" ? source : (EN[source] || source);
}

export function localizeHouseholdTasksTree(root, hass) {
  if (householdTasksLocale(hass) === "de" || !root) return;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);
  for (const node of nodes) {
    if (["STYLE", "SCRIPT"].includes(node.parentElement?.tagName)) continue;
    const trimmed = node.textContent.trim();
    if (!trimmed || !EN[trimmed]) continue;
    node.textContent = node.textContent.replace(trimmed, EN[trimmed]);
  }
  root.querySelectorAll("[title],[placeholder],[aria-label]").forEach((element) => {
    for (const attribute of ["title", "placeholder", "aria-label"]) {
      const value = element.getAttribute(attribute);
      if (value && EN[value]) element.setAttribute(attribute, EN[value]);
    }
  });
}
